package ems.db;

import ems.model.Address;
import ems.model.Employee;
import ems.model.SearchField;
import ems.error.ValidationException;
import java.math.BigDecimal;
import java.sql.*;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.function.Supplier;

/** All SQL for employees and the tables that hang off them (address, division, job title). */
public class EmployeeDao {
    private static final String SELECT =
        "SELECT e.empID, e.fname, e.lname, e.email, e.hireDate, e.salary, e.SSN, e.DOB, e.phone, "
        + "e.emergency_contact_name, e.emergency_contact_phone, a.street, c.city_name, s.abbrev, a.zip, "
        + "ed.divID, d.name AS divName, ej.job_titleID, jt.job_title "
        + "FROM employees e "
        + "LEFT JOIN addresses a ON a.addressID = e.addressID "
        + "LEFT JOIN cities c ON c.cityID = a.cityID "
        + "LEFT JOIN states s ON s.stateID = a.stateID "
        + "LEFT JOIN employee_division ed ON ed.empID = e.empID "
        + "LEFT JOIN division d ON d.divID = ed.divID "
        + "LEFT JOIN employee_job_titles ej ON ej.empID = e.empID "
        + "LEFT JOIN job_titles jt ON jt.job_titleID = ej.job_titleID ";
    private static final String ORDER = " ORDER BY e.lname, e.fname";

    private final Supplier<Connection> source;

    public EmployeeDao(Supplier<Connection> source) { this.source = source; }

    public Optional<Employee> findById(int empID) {
        List<Employee> rows = query(SELECT + "WHERE e.empID = ?", ps -> ps.setInt(1, empID));
        return rows.stream().findFirst();
    }

    public List<Employee> search(SearchField field, String value) {
        switch (field) {
            case EMPID: return query(SELECT + "WHERE e.empID = ?" + ORDER, ps -> ps.setInt(1, Integer.parseInt(value)));
            case DOB:   return query(SELECT + "WHERE e.DOB = ?" + ORDER, ps -> ps.setDate(1, Date.valueOf(LocalDate.parse(value))));
            case SSN:   return query(SELECT + "WHERE e.SSN = ?" + ORDER, ps -> ps.setString(1, value));
            default:
                String like = "%" + value.toLowerCase().replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%";
                return query(SELECT + "WHERE LOWER(e.fname) LIKE ? OR LOWER(e.lname) LIKE ?" + ORDER,
                    ps -> { ps.setString(1, like); ps.setString(2, like); });
        }
    }

    public List<Employee> hiredBetween(LocalDate start, LocalDate end) {
        return query(SELECT + "WHERE e.hireDate BETWEEN ? AND ? ORDER BY e.hireDate DESC, e.empID DESC",
            ps -> { ps.setDate(1, Date.valueOf(start)); ps.setDate(2, Date.valueOf(end)); });
    }

    /** Updates every table for one employee in a single transaction. */
    public void update(Employee e) {
        try (Connection c = source.get()) {
            c.setAutoCommit(false);
            try {
                Integer addressID = addressIdFor(c, e.getAddress());
                try (PreparedStatement ps = c.prepareStatement(
                        "UPDATE employees SET fname=?, lname=?, email=?, hireDate=?, salary=?, SSN=?, DOB=?, phone=?, "
                        + "emergency_contact_name=?, emergency_contact_phone=?, addressID=? WHERE empID=?")) {
                    bindEmployee(ps, e, addressID);
                    ps.setInt(12, e.getEmpID());
                    if (ps.executeUpdate() == 0) throw new ValidationException("Employee not found");
                }
                linkDivisionAndJob(c, e.getEmpID(), e.getDivID(), e.getJobTitleID());
                c.commit();
            } catch (RuntimeException | SQLException ex) {
                SqlSupport.rollbackQuietly(c);
                throw ex;
            }
        } catch (SQLException ex) {
            throw SqlSupport.translate(ex);
        }
    }

    /** Inserts a new employee; empID is generated by the database. Returns the new empID. */
    public int insert(Employee e) {
        try (Connection c = source.get()) {
            c.setAutoCommit(false);
            try {
                Integer addressID = addressIdFor(c, e.getAddress());
                int newID;
                try (PreparedStatement ps = c.prepareStatement(
                        "INSERT INTO employees (fname, lname, email, hireDate, salary, SSN, DOB, phone, "
                        + "emergency_contact_name, emergency_contact_phone, addressID) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                        Statement.RETURN_GENERATED_KEYS)) {
                    bindEmployee(ps, e, addressID);
                    ps.executeUpdate();
                    try (ResultSet keys = ps.getGeneratedKeys()) { keys.next(); newID = keys.getInt(1); }
                }
                linkDivisionAndJob(c, newID, e.getDivID(), e.getJobTitleID());
                c.commit();
                return newID;
            } catch (RuntimeException | SQLException ex) {
                SqlSupport.rollbackQuietly(c);
                throw ex;
            }
        } catch (SQLException ex) {
            throw SqlSupport.translate(ex);
        }
    }

    /** Deletes the employee and dependent rows in one transaction. Returns false when no such employee exists. */
    public boolean delete(int empID) {
        try (Connection c = source.get()) {
            c.setAutoCommit(false);
            try {
                Integer addressID = null;
                try (PreparedStatement ps = c.prepareStatement("SELECT addressID FROM employees WHERE empID = ?")) {
                    ps.setInt(1, empID);
                    try (ResultSet rs = ps.executeQuery()) {
                        if (!rs.next()) return false;
                        addressID = (Integer) rs.getObject(1);
                    }
                }
                for (String table : new String[] {"payroll", "employee_division", "employee_job_titles", "employees"}) {
                    try (PreparedStatement ps = c.prepareStatement("DELETE FROM " + table + " WHERE empID = ?")) {
                        ps.setInt(1, empID);
                        ps.executeUpdate();
                    }
                }
                if (addressID != null) { // keep the address while a roommate still uses it
                    try (PreparedStatement ps = c.prepareStatement(
                            "DELETE FROM addresses WHERE addressID = ? AND NOT EXISTS (SELECT 1 FROM employees WHERE addressID = ?)")) {
                        ps.setInt(1, addressID);
                        ps.setInt(2, addressID);
                        ps.executeUpdate();
                    }
                }
                c.commit();
                return true;
            } catch (RuntimeException | SQLException ex) {
                SqlSupport.rollbackQuietly(c);
                throw ex;
            }
        } catch (SQLException ex) {
            throw SqlSupport.translate(ex);
        }
    }

    /** Raises salaries below the limit by percent. Returns the number of rows changed. */
    public int raiseSalaryBelow(BigDecimal percent, BigDecimal limit) {
        return updateSalaries("salary < ?", percent, ps -> ps.setBigDecimal(2, limit));
    }

    /** Raises salaries between min and max (inclusive) by percent. Returns the number of rows changed. */
    public int raiseSalaryBetween(BigDecimal percent, BigDecimal min, BigDecimal max) {
        return updateSalaries("salary BETWEEN ? AND ?", percent, ps -> { ps.setBigDecimal(2, min); ps.setBigDecimal(3, max); });
    }

    // ---------- helpers ----------

    private interface Binder { void bind(PreparedStatement ps) throws SQLException; }

    private int updateSalaries(String where, BigDecimal percent, Binder rest) {
        try (Connection c = source.get();
             PreparedStatement ps = c.prepareStatement("UPDATE employees SET salary = ROUND(salary * (1 + ? / 100), 2) WHERE " + where)) {
            ps.setBigDecimal(1, percent);
            rest.bind(ps);
            return ps.executeUpdate();
        } catch (SQLException ex) {
            throw SqlSupport.translate(ex);
        }
    }

    private List<Employee> query(String sql, Binder binder) {
        try (Connection c = source.get(); PreparedStatement ps = c.prepareStatement(sql)) {
            binder.bind(ps);
            List<Employee> out = new ArrayList<>();
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) out.add(map(rs));
            }
            return out;
        } catch (SQLException ex) {
            throw SqlSupport.translate(ex);
        }
    }

    private static Employee map(ResultSet rs) throws SQLException {
        Employee e = new Employee();
        e.setEmpID(rs.getInt("empID"));
        e.setFname(rs.getString("fname"));
        e.setLname(rs.getString("lname"));
        e.setEmail(rs.getString("email"));
        Date hire = rs.getDate("hireDate");
        e.setHireDate(hire == null ? null : hire.toLocalDate());
        e.setSalary(rs.getBigDecimal("salary"));
        e.setSsn(rs.getString("SSN"));
        Date dob = rs.getDate("DOB");
        e.setDob(dob == null ? null : dob.toLocalDate());
        e.setPhone(rs.getString("phone"));
        e.setEmergencyName(rs.getString("emergency_contact_name"));
        e.setEmergencyPhone(rs.getString("emergency_contact_phone"));
        e.setAddress(new Address(rs.getString("street"), rs.getString("city_name"), rs.getString("abbrev"), rs.getString("zip")));
        e.setDivID(rs.getInt("divID"));
        e.setDivisionName(rs.getString("divName"));
        e.setJobTitleID(rs.getInt("job_titleID"));
        e.setJobTitle(rs.getString("job_title"));
        return e;
    }

    private static void bindEmployee(PreparedStatement ps, Employee e, Integer addressID) throws SQLException {
        ps.setString(1, e.getFname());
        ps.setString(2, e.getLname());
        ps.setString(3, e.getEmail());
        ps.setDate(4, e.getHireDate() == null ? null : Date.valueOf(e.getHireDate()));
        ps.setBigDecimal(5, e.getSalary());
        ps.setString(6, e.getSsn());
        ps.setDate(7, e.getDob() == null ? null : Date.valueOf(e.getDob()));
        ps.setString(8, e.getPhone());
        ps.setString(9, e.getEmergencyName());
        ps.setString(10, e.getEmergencyPhone());
        ps.setObject(11, addressID);
    }

    private static void linkDivisionAndJob(Connection c, int empID, int divID, int jobTitleID) throws SQLException {
        try (PreparedStatement ps = c.prepareStatement(
                "INSERT INTO employee_division (empID, divID) VALUES (?, ?) ON DUPLICATE KEY UPDATE divID = VALUES(divID)")) {
            ps.setInt(1, empID); ps.setInt(2, divID); ps.executeUpdate();
        }
        try (PreparedStatement ps = c.prepareStatement(
                "INSERT INTO employee_job_titles (empID, job_titleID) VALUES (?, ?) ON DUPLICATE KEY UPDATE job_titleID = VALUES(job_titleID)")) {
            ps.setInt(1, empID); ps.setInt(2, jobTitleID); ps.executeUpdate();
        }
    }

    /** Finds the matching addresses row or creates it, so roommates share one row. Null when no address was given. */
    private static Integer addressIdFor(Connection c, Address a) throws SQLException {
        if (a == null || a.isEmpty()) return null;
        int cityID = idOrInsert(c, "SELECT cityID FROM cities WHERE city_name = ?", "INSERT INTO cities (city_name) VALUES (?)", a.getCity());
        int stateID;
        try (PreparedStatement ps = c.prepareStatement("SELECT stateID FROM states WHERE abbrev = ?")) {
            ps.setString(1, a.getState());
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) throw new ValidationException("Unknown state: " + a.getState());
                stateID = rs.getInt(1);
            }
        }
        try (PreparedStatement ps = c.prepareStatement(
                "SELECT addressID FROM addresses WHERE street = ? AND cityID = ? AND stateID = ? AND zip = ? LIMIT 1")) {
            ps.setString(1, a.getStreet()); ps.setInt(2, cityID); ps.setInt(3, stateID); ps.setString(4, a.getZip());
            try (ResultSet rs = ps.executeQuery()) { if (rs.next()) return rs.getInt(1); }
        }
        try (PreparedStatement ps = c.prepareStatement(
                "INSERT INTO addresses (street, cityID, stateID, zip) VALUES (?,?,?,?)", Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, a.getStreet()); ps.setInt(2, cityID); ps.setInt(3, stateID); ps.setString(4, a.getZip());
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) { keys.next(); return keys.getInt(1); }
        }
    }

    private static int idOrInsert(Connection c, String select, String insert, String value) throws SQLException {
        try (PreparedStatement ps = c.prepareStatement(select)) {
            ps.setString(1, value);
            try (ResultSet rs = ps.executeQuery()) { if (rs.next()) return rs.getInt(1); }
        }
        try (PreparedStatement ps = c.prepareStatement(insert, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, value);
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) { keys.next(); return keys.getInt(1); }
        }
    }
}
